#!/usr/bin/env python
"""Assemble reports/methodology_results.md and refresh the README results block.

    python scripts/write_report.py

reports/methodology_results.md = reports/methodology.md + generated results (results/tables.md)
+ figure index + reports/discussion.md (hand-written interpretation, if present).
README.md: the text between <!-- RESULTS:START --> and <!-- RESULTS:END --> is replaced by a compact
summary computed from results/ files, so every number in the README is traceable to results/.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from stance.utils import abs_path  # noqa: E402

FIGURES = [
    ("label_distribution.png", "Label distribution per split"),
    ("label_by_source_type.png", "Training labels per source type"),
    ("script_distribution.png", "Script distribution, train vs gold"),
    ("source_type_vs_gold.png", "Length and code-mixing: training text vs hand-written comments"),
    ("top_ngrams.png", "Top n-grams per class and language"),
    ("robustness_heatmap.png", "Challenge-suite failure rate per category and model"),
    ("tfidf_top_features.png", "Largest TF-IDF coefficients per class"),
    ("error_taxonomy.png", "Error taxonomy and per-category errors, baseline vs final"),
]


def summary_block() -> str:
    lines = ["<!-- RESULTS:START -->", "_Generated by `scripts/write_report.py` from `results/`; do not edit by hand._", ""]
    fj = abs_path("results/final.json")
    rows = []
    if fj.exists():
        d = json.loads(fj.read_text(encoding="utf-8"))
        g = d["final_gold"]
        c = {r["candidate"]: r for r in d["candidates"]}
        fc = d["final"].get("candidate")
        rows.append({"system": f"**Final: {fc}**", "gold macro F1": g["macro_f1"],
                     "gold hi": g["per_language"].get("hi", {}).get("macro_f1"), "gold bn": g["per_language"].get("bn", {}).get("macro_f1"),
                     "challenge fail": d["final_challenge"].get("overall_fail_rate"), "dev macro F1": c.get(fc, {}).get("dev_macro_f1")})
    b = abs_path("results/baselines.csv")
    if b.exists():
        from stance.evaluation.select import baseline_to_beat

        bt = pd.read_csv(b)
        name = baseline_to_beat()
        r = bt[bt.model == name].iloc[0]
        rows.append({"system": f"Baseline to beat: {name}", "gold macro F1": r.gold_macro_f1, "gold hi": r.gold_f1_hi, "gold bn": r.gold_f1_bn,
                     "challenge fail": r.challenge_fail_rate, "dev macro F1": r.dev_macro_f1})
        lx = bt[bt.model == "lexicon"]
        if len(lx):
            r = lx.iloc[0]
            rows.append({"system": "Lexicon rules (optimistic, see note)", "gold macro F1": r.gold_macro_f1, "gold hi": r.gold_f1_hi,
                         "gold bn": r.gold_f1_bn, "challenge fail": r.challenge_fail_rate, "dev macro F1": r.dev_macro_f1})
    sig = abs_path("results/significance.csv")
    if rows:
        lines += [pd.DataFrame(rows).to_markdown(index=False, floatfmt=".3f"), ""]
    if sig.exists():
        s = pd.read_csv(sig)
        dcol = [c for c in s.columns if c.startswith("diff_vs_")][0]
        n_sig = int((s["significant"] & (s[dcol] > 0)).sum())
        lines.append(f"Paired bootstrap on the gold set (`results/significance.csv`): {n_sig} system(s) are significantly better "
                     f"than the baseline to beat at 95 % confidence.")
    cost = None
    if fj.exists():
        cost = pd.DataFrame(json.loads(fj.read_text(encoding="utf-8")).get("accuracy_vs_cost", []))
    if cost is not None and len(cost):
        lines += ["", "Accuracy vs cost on CPU:", "", cost.to_markdown(index=False, floatfmt=".3f")]
    lines += ["", "All tables: [results/tables.md](results/tables.md). Full report: [reports/methodology_results.md](reports/methodology_results.md).",
              "<!-- RESULTS:END -->"]
    return "\n".join(lines)


def main() -> None:
    parts = [abs_path("reports/methodology.md").read_text(encoding="utf-8"), "\n# Results\n"]
    t = abs_path("results/tables.md")
    if t.exists():
        parts.append(t.read_text(encoding="utf-8").split("\n", 1)[1].replace("### ", "## "))
    figs = [f"* ![{cap}](../results/figures/{f}) {cap}" for f, cap in FIGURES if abs_path(f"results/figures/{f}").exists()]
    if figs:
        parts += ["\n## Figures\n", "\n".join(figs)]
    disc = abs_path("reports/discussion.md")
    if disc.exists():
        parts += ["\n", disc.read_text(encoding="utf-8")]
    abs_path("reports/methodology_results.md").write_text("\n".join(parts), encoding="utf-8")
    readme = abs_path("README.md")
    txt = readme.read_text(encoding="utf-8")
    block = summary_block()
    if "<!-- RESULTS:START -->" in txt:
        pre = txt.split("<!-- RESULTS:START -->")[0]
        post = txt.split("<!-- RESULTS:END -->")[1]
        txt = pre + block + post
    else:
        txt = txt.replace("## Methodology summary", block + "\n\n## Methodology summary", 1)
    readme.write_text(txt, encoding="utf-8")
    print("-> reports/methodology_results.md, README.md results block")


if __name__ == "__main__":
    main()
